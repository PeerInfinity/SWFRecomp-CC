#!/usr/bin/env python3
"""Generate the AVM1 native-object table from the FP32 decls golden.

Input: a `global_proto_decls`-format dump (ruffle-tests/tests/swfs/avm1/global_proto_decls/output.txt,
which is byte-identical to a pinned FP32 32,0,0,465 LNX capture; s30 pre-launch-oracles/native-table).
Each `Testing PATH` section lists, in Flash for..in order, every member visible after
ASSetPropFlags(obj, null, 0, 1): `  key[, own][, DONT_ENUM][, READ_ONLY], type=[t]`.

Only OWN members are facts about PATH's object (inherited ones belong to its __proto__). The flags
are those of the object's FIRST visit: the test unhides own props as it walks, and one object can
be reached through several paths (System.security.__constructor__.prototype IS Object.prototype),
so the runtime applies entries in golden order and skips an object it has already reconciled.

Output: a C include (static tables) consumed by avm1NativeTableApply() in action.c.

Usage: gen_avm1_native_table.py GOLDEN OUT.inc [--only REGEX] [--exclude REGEX]

Regenerate the committed table (byte-identical, checked s30 w2-native-table-land):
  python3 scripts/gen_avm1_native_table.py \
      ruffle-tests/tests/swfs/avm1/global_proto_decls/output.txt \
      SWFModernRuntime/include/actionmodern/avm1_native_table.inc \
      --delete-golden ruffle-tests/tests/swfs/avm1/global_proto_decls_delete/output.txt
"""
import re, sys, argparse

# The test's `enumerated = {}` inherits Object.prototype, so `enumerated[k]` is truthy for these
# names whatever k's real attribute is: DONT_ENUM is UNOBSERVABLE for them in the golden (attr 4).
OBJ_PROTO_NAMES = {'watch', 'unwatch', 'addProperty', 'valueOf', 'toString', 'hasOwnProperty',
                   'isPrototypeOf', 'isPropertyEnumerable', 'toLocaleString', 'constructor', '__proto__'}

# READ_ONLY in the golden means "a write of 'OTHER' did not read back". For a primitive member that is
# either a real constant (Math.E) or a coercing native accessor (System.exactSettings: 'OTHER' -> true),
# and on a prototype it is a native getter whose setter no-ops for this=prototype (MovieClip.prototype.
# blendMode). Only numbers are taken as constants; the other primitive types are UNOBSERVABLE (attr 32).
RO_AMBIGUOUS_TYPES = {'boolean', 'string', 'undefined', 'null'}

TYPES = ['object', 'function', 'function with prototype', 'number', 'string', 'boolean',
         'null', 'undefined', 'movieclip']

def parse(path):
    secs, order, cur = {}, [], None
    for line in open(path, encoding='utf-8').read().split('\n'):
        if line.startswith('Testing '):
            name = line[8:]
            cur = None if name in secs else name
            if cur is not None:
                secs[cur] = []; order.append(cur)
            continue
        m = re.match(r'  (.*?)((?:, own)?(?:, DONT_ENUM)?(?:, READ_ONLY)?), type=\[(.*)\]$', line)
        if m and cur is not None:
            key, fl, t = m.group(1), m.group(2), m.group(3)
            if ', own' in fl:
                secs[cur].append((key, 'DONT_ENUM' in fl, 'READ_ONLY' in fl, t))
    return order, secs

def parse_delete(path):
    """`Testing PATH` + `  key, DONT_DELETE` lines: the members that survived `delete`."""
    out, cur = {}, None
    for line in open(path, encoding='utf-8').read().split('\n'):
        if line.startswith('Testing '):
            cur = line[8:]
            out.setdefault(cur, set())
        elif line.startswith('  ') and line.endswith(', DONT_DELETE') and cur is not None:
            out[cur].add(line[2:-len(', DONT_DELETE')])
    return out

def cstr(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('golden'); ap.add_argument('out')
    ap.add_argument('--only'); ap.add_argument('--exclude')
    ap.add_argument('--delete-golden', help='global_proto_decls_delete output.txt: adds the DONT_DELETE column')
    a = ap.parse_args()
    order, secs = parse(a.golden)
    dd = parse_delete(a.delete_golden) if a.delete_golden else {}
    if a.only: order = [p for p in order if re.search(a.only, p)]
    if a.exclude: order = [p for p in order if not re.search(a.exclude, p)]
    out = ['// GENERATED by scripts/gen_avm1_native_table.py from ' + a.golden.split('ruffle-tests/')[-1],
           '// (Ruffle test golden, tests/tests/swfs/avm1/global_proto_decls/output.txt in ruffle-rs/ruffle)',
           '// DO NOT EDIT. One object row per `Testing PATH` section (first visit), members in FP32',
           '// for..in order. attrs: 1=DONT_ENUM 2=READ_ONLY 4=DONT_ENUM unobservable (keep ours)\n// 8=DONT_DELETE known 16=DONT_DELETE 32=READ_ONLY unobservable (keep ours); type: index into AVM1NT_T_*.', '']
    for i, t in enumerate(TYPES):
        out.append('#define AVM1NT_T_%s %d' % (re.sub(r'\W', '_', t).upper(), i))
    out += ['', 'typedef struct { const char* name; unsigned char attrs; unsigned char type; } Avm1NtMember;',
            'typedef struct { const char* path; unsigned short first; unsigned short count; } Avm1NtObject;', '',
            'static const Avm1NtMember g_avm1nt_members[] = {']
    objs, n = [], 0
    for p in order:
        mem = secs[p]
        objs.append((p, n, len(mem)))
        for key, de, ro, t in mem:
            at = (1 if de else 0) | (2 if ro else 0) | (4 if key in OBJ_PROTO_NAMES else 0)
            if t in RO_AMBIGUOUS_TYPES:
                at = (at & ~2) | 32
            if p in dd:   # section present in the delete golden: DONT_DELETE is known for own members
                at |= 8 | (16 if key in dd[p] else 0)
            out.append('\t{%s, %d, %d},' % (cstr(key), at, TYPES.index(t)))
            n += 1
    out += ['\t{0, 0, 0}', '};', '', 'static const Avm1NtObject g_avm1nt_objects[] = {']
    for p, f, c in objs:
        out.append('\t{%s, %d, %d},' % (cstr(p), f, c))
    out += ['};', '#define AVM1NT_NUM_OBJECTS %d' % len(objs), '']
    open(a.out, 'w').write('\n'.join(out))
    print('objects=%d members=%d' % (len(objs), n), file=sys.stderr)

if __name__ == '__main__':
    main()
