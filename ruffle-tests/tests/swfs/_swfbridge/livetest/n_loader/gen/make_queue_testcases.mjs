// make_queue_testcases.mjs - generate a small batch of flat "walk right" levels
// (authored constructions in N's format, NOT N's proprietary built-in data) to
// exercise the batch-verify QUEUE on Ruffle: one page session, the host serves
// these levels one after another, the SWF re-loads each after completing the
// previous one. Writes the browser global file n_queue_testcases.js.
//
//   node gen/make_queue_testcases.mjs   # -> ../n_queue_testcases.js
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { Level, OBJ, TILE_FULL } from "./nLevel.js";
import { holdRight } from "./nDemo.js";

// Match the proven walk fixture: floor map-row 14, everything rests at y=350.
const FLOOR_ROW = 14;
const REST_Y = 350;
const FLOOR_X0 = 5;
const FLOOR_X1 = 20; // tile centers 156..516px -> covers spawn..door below

// Player walks right, hits the switch (opens the door), then the door. Switch
// must be passed before the door, so spawnX < switchX < doorX.
function flatWalk(id, spawnX, switchX, doorX) {
	const lvl = new Level();
	for (let mx = FLOOR_X0; mx <= FLOOR_X1; mx++) lvl.setTile(mx, FLOOR_ROW, TILE_FULL);
	lvl.addObject(OBJ.PLAYER, [spawnX, REST_Y]);
	lvl.addObject(OBJ.EXIT, [doorX, REST_Y, switchX, REST_Y]); // [doorX,doorY,switchX,switchY]
	const dist = doorX - spawnX;
	const ticks = Math.max(28, Math.ceil(dist / 3) + 20); // generous hold-right margin
	return { levelId: id, level: lvl.encode(), demo: holdRight(ticks), _meta: { spawnX, switchX, doorX, dist, ticks } };
}

const cases = [
	flatWalk("q0", 240, 270, 300), // 60px walk
	flatWalk("q1", 240, 300, 340), // 100px
	flatWalk("q2", 240, 330, 380), // 140px
];

const here = dirname(fileURLToPath(import.meta.url));
const outPath = join(here, "..", "n_queue_testcases.js");

// Strip the _meta before emitting the browser payload (keep it for the log).
const payload = cases.map(({ levelId, level, demo }) => ({ levelId, level, demo }));
const banner =
	"// n_queue_testcases.js - GENERATED by gen/make_queue_testcases.mjs.\n" +
	"// Authored flat walk-right levels (N format) for the Ruffle batch-verify\n" +
	"// queue test. Not N's proprietary built-in data. Edit the generator, not this.\n";
writeFileSync(outPath, banner + "window.__N_QUEUE = " + JSON.stringify(payload, null, 2) + ";\n");

console.log(`wrote ${payload.length} levels -> ${outPath}`);
for (const c of cases) {
	console.log(`  ${c.levelId}: spawn ${c._meta.spawnX} -> switch ${c._meta.switchX} -> door ${c._meta.doorX}` +
		` (${c._meta.dist}px, demo ${c._meta.ticks} ticks)`);
}
